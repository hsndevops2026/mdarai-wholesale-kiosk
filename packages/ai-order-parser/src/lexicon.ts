/**
 * Palestinian Arabic + Hebrew vocabulary for the deterministic parser.
 * Keys are written naturally and normalised at load time, so spelling
 * variants (ة/ه, أ/ا, Hebrew final letters) do not need to be listed twice.
 */

function normMap<T>(entries: Array<[string[], T]>): Map<string, T> {
  const m = new Map<string, T>();
  for (const [words, value] of entries) for (const w of words) m.set(normalizeText(w), value);
  return m;
}

function normSet(words: string[]): Set<string> {
  return new Set(words.map((w) => normalizeText(w)));
}

